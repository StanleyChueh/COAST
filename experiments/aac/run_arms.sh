#!/usr/bin/env bash
# Run fixed-h / AAC arms against already-running AAC servers (see serve_aac.sh).
#
# Every arm uses identical tasks, scene seeds (episode k <- env.reset(seed=SEED+k)),
# split, preprocessing (native 256x256 images), checkpoint, denoising steps and
# server; the only intended difference is how many actions of candidate 0 are
# executed per policy call. Arms are spread round-robin over PORTS; arms sharing
# a port run sequentially, ports run in parallel.
#
#   RUN=phaseA_pilot TASKS="OpenDrawer CloseFridge" EPISODES=20 \
#   ARMS="fixed2 fixed4 fixed8 fixed12 fixed16 aac" PORTS="8000 8001" WORKERS=4 \
#   experiments/aac/run_arms.sh
#
# Arm names: fixed<h> (h in 1..16) or aac*. Each (arm, task) runs one main.py
# client that RESUMES from the first episode not yet in
# arms/<arm>/logs/<task>/episodes.jsonl (scenes depend only on the episode seed,
# so resuming is exact). A client killed by a simulator/EGL error or OOM is
# resumed up to MAX_ATTEMPTS times; every attempt is recorded in
# arms/<arm>/attempts.log and its output in arms/<arm>/task_logs/<task>.log.
# Rerunning the script with the same RUN therefore only fills in what is missing.
#
# Memory: each RoboCasa client holds ~4-5 GB RSS; keep (#ports x WORKERS) x 5 GB
# well under host RAM (62 GB here -> WORKERS<=4 with 2 ports).
# EGL_DEVICES="0 1" (optional) renders arms on port i with MUJOCO_EGL_DEVICE_ID=EGL_DEVICES[i].
#
# Do not edit this file while it is running: bash reads scripts incrementally.
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
RUN=${RUN:?set RUN}
TASKS=${TASKS:?set TASKS}
EPISODES=${EPISODES:-20}
ARMS=${ARMS:-"fixed2 fixed4 fixed8 fixed12 fixed16 aac"}
PORTS=${PORTS:-8000}
WORKERS=${WORKERS:-4}
SEED=${SEED:-0}
SPLIT=${SPLIT:-pretrain}
RESIZE=${RESIZE:-256}
MAX_STEPS=${MAX_STEPS:-}
MAX_ATTEMPTS=${MAX_ATTEMPTS:-4}
EGL_DEVICES=${EGL_DEVICES:-}
RUN_DIR="$REPO/results/aac/$RUN"
mkdir -p "$RUN_DIR/arms"
export REPO RUN_DIR EPISODES SEED SPLIT RESIZE MAX_STEPS MAX_ATTEMPTS

stamp=$(date +%Y%m%dT%H%M%S)
cat > "$RUN_DIR/run_config.$stamp.json" <<EOF
{"run": "$RUN", "tasks": "$TASKS", "episodes_per_task": $EPISODES, "arms": "$ARMS",
 "ports": "$PORTS", "workers_per_arm": $WORKERS, "seed": $SEED, "seed_per_episode": true,
 "split": "$SPLIT", "resize_size": $RESIZE, "max_steps": "${MAX_STEPS:-default(1.5*task_horizon)}",
 "save_video": false, "egl_devices": "$EGL_DEVICES"}
EOF
cp "$RUN_DIR/run_config.$stamp.json" "$RUN_DIR/run_config.json"
# Manifest + code snapshot per invocation (a resumed run keeps every snapshot).
(cd "$REPO/examples/robocasa_env" && uv run --frozen python ../../experiments/aac/write_manifest.py \
    --run_dir "$RUN_DIR" $(for p in $PORTS; do echo --port "$p"; done) --config "$RUN_DIR/run_config.json" \
    -- "$0 RUN=$RUN TASKS=$TASKS EPISODES=$EPISODES ARMS=$ARMS PORTS=$PORTS WORKERS=$WORKERS SEED=$SEED")
cp "$RUN_DIR/manifest.json" "$RUN_DIR/manifest.$stamp.json"
git -C "$REPO" diff HEAD > "$RUN_DIR/code_snapshot.$stamp.diff"
git -C "$REPO" ls-files --others --exclude-standard -z \
    | tar -C "$REPO" --null -T - -czf "$RUN_DIR/code_snapshot_untracked.$stamp.tgz"

mode_args_for() {
    case "$1" in
        aac*) echo "--execution_mode aac" ;;
        fixed*) echo "--execution_mode fixed --replan_steps ${1#fixed}" ;;
        *) echo "unknown arm $1" >&2; return 1 ;;
    esac
}

# run_task <arm> <port> <task>: run/resume one (arm, task) until EPISODES are logged.
run_task() {
    local arm=$1 port=$2 task=$3
    local dir="$RUN_DIR/arms/$arm"
    local f="$dir/logs/$task/episodes.jsonl"
    local extra=()
    [[ -n "$MAX_STEPS" ]] && extra+=(--max_steps "$MAX_STEPS")
    mkdir -p "$dir/task_logs"
    local attempt done_n kind
    for (( attempt = 1; attempt <= MAX_ATTEMPTS; attempt++ )); do
        done_n=0
        [[ -f "$f" ]] && done_n=$(wc -l < "$f")
        (( done_n >= EPISODES )) && return 0
        kind=start
        (( attempt > 1 || done_n > 0 )) && kind=resume
        echo "$(date -Is) $kind $task at episode $done_n/$EPISODES (attempt $attempt)" >> "$dir/attempts.log"
        # shellcheck disable=SC2046
        (cd "$REPO/examples/robocasa_env" && MUJOCO_GL=egl uv run --frozen python main.py \
            --port "$port" --env_name "$task" --split "$SPLIT" \
            --start_episode "$done_n" --num_episodes $(( EPISODES - done_n )) \
            --seed "$SEED" --seed_per_episode --resize_size "$RESIZE" --no-save_video \
            $(mode_args_for "$arm") "${extra[@]}" \
            --log_dir "$dir/logs" --output_dir "$dir/videos") >> "$dir/task_logs/$task.log" 2>&1 || true
    done
    done_n=0
    [[ -f "$f" ]] && done_n=$(wc -l < "$f")
    (( done_n >= EPISODES )) || echo "$(date -Is) GAVE UP $task at $done_n/$EPISODES" >> "$dir/attempts.log"
}
export -f run_task mode_args_for

run_arm() {
    local arm=$1 port=$2
    mkdir -p "$RUN_DIR/arms/$arm"
    echo "[$arm] port=$port start $(date -Is)"
    printf '%s\n' $TASKS | xargs -P "$WORKERS" -I{} bash -c 'run_task "$0" "$1" "$2"' "$arm" "$port" {}
    echo "[$arm] port=$port end $(date -Is)"
}

read -r -a ports <<< "$PORTS"
read -r -a arms <<< "$ARMS"
read -r -a egl <<< "$EGL_DEVICES"
for i in "${!ports[@]}"; do
    (
        if [[ -n "${egl[$i]:-}" ]]; then export MUJOCO_EGL_DEVICE_ID="${egl[$i]}"; fi
        for j in "${!arms[@]}"; do
            if (( j % ${#ports[@]} == i )); then run_arm "${arms[$j]}" "${ports[$i]}"; fi
        done
    ) &
done
wait
echo "all arms finished: $RUN_DIR"
